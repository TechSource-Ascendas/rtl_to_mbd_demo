%[text] # From Verilog to Model-Based Design - Demo Overview
%[text] A four-part, GUI-first walkthrough for RTL engineers who are moving their FPGA work to Simulink. All four parts use **one** example - a 4-tap low-pass FIR filter - so every result can be compared bit for bit with the previous one.
%[text:table]
%[text] | Part | Live script | Question it answers |
%[text] | --- | --- | --- |
%[text] | 1 | `Part1_Equation_to_Simulink.m` | How do I think in MBD? Equation -> blocks -> Fixed-Point Tool -> generated Verilog, plus FSMs in Stateflow |
%[text] | 2 | `Part2_Import_Existing_HDL.m` | What do I do with my existing Verilog? importhdl vs. BlackBox/DocBlock vs. cosimulation, and which RTL coding patterns importhdl accepts |
%[text] | 3 | `Part3_Custom_Reference_Design_ArtyA7.m` | How do I target my own board? Custom board + reference design for the Digilent Arty A7-35T, and where the templates come from |
%[text] | 4 | `Part4_HDL_Cosimulation.m` | How do I prove my RTL matches the model? HDL cosimulation with Vivado Simulator, including keeping your own Verilog testbench |
%[text:table]
%[text] ## Folder layout
%[text:table]
%[text] | Folder | Content |
%[text] | --- | --- |
%[text] | `models` | Finished models: `fir_mbd`, `fir_mbd_float`, `fir_fsm` (Part 1), `fir_import_compare`, `fir_blackbox` (Part 2), `fir_arty_ip` (Part 3) |
%[text] | `hdl_src` | The "legacy" hand-written RTL `fir4_legacy.v` and its Verilog testbench `tb_fir4_legacy.v` |
%[text] | `hdlimport` | Model generated by `importhdl` (Part 2) |
%[text] | `arty_a7_35t` | Board and reference design plugin for the Arty A7-35T, the Vivado block-design project and a prebuilt bitstream (Part 3) |
%[text] | `cosim_work` | Cosimulation Wizard output and test bench `fir_cosim_tb` (Part 4) |
%[text] | `cosim_tb_work` | Cosimulation driven by the Verilog testbench, checker model `fir_vtb_check` (Part 4, section 9) |
%[text] | `importhdl_examples` | 24 small Verilog files showing which coding patterns `importhdl` accepts (Part 2) |
%[text:table]
