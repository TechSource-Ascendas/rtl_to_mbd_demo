function hB = plugin_board()
% Board definition: Digilent Arty A7-35T  (XC7A35T-1LICSG324)
%   Pin numbers and I/O standards are taken from Digilent's
%   Arty-A7-35-Master.xdc.  All user I/O on this board is 3.3 V (LVCMOS33).

hB = hdlcoder.Board;

hB.BoardName    = 'Digilent Arty A7-35T (custom)';

% FPGA device
hB.FPGAVendor   = 'Xilinx';
hB.FPGAFamily   = 'Artix7';
hB.FPGADevice   = 'xc7a35ti';
hB.FPGAPackage  = 'csg324';
hB.FPGASpeed    = '-1L';

% Tool
hB.SupportedTool = {'Xilinx Vivado'};

% The FPGA is the only device on the on-board USB-JTAG chain
hB.JTAGChainPosition = 1;

%% Board I/O that the DUT ports can be mapped to (Set Target Interface table)
hB.addExternalIOInterface( ...
    'InterfaceID',     'LEDs General Purpose', ...
    'InterfaceType',   'OUT', ...
    'PortName',        'GPLEDs', ...
    'PortWidth',       4, ...
    'FPGAPin',         {'H5', 'J5', 'T9', 'T10'}, ...          % LD4..LD7
    'IOPadConstraint', {'IOSTANDARD = LVCMOS33'});

hB.addExternalIOInterface( ...
    'InterfaceID',     'Slide switches', ...
    'InterfaceType',   'IN', ...
    'PortName',        'GPSW', ...
    'PortWidth',       4, ...
    'FPGAPin',         {'A8', 'C11', 'C10', 'A10'}, ...        % SW0..SW3
    'IOPadConstraint', {'IOSTANDARD = LVCMOS33'});

hB.addExternalIOInterface( ...
    'InterfaceID',     'Push buttons', ...
    'InterfaceType',   'IN', ...
    'PortName',        'GPBTN', ...
    'PortWidth',       4, ...
    'FPGAPin',         {'D9', 'C9', 'B9', 'B8'}, ...           % BTN0..BTN3
    'IOPadConstraint', {'IOSTANDARD = LVCMOS33'});

hB.addExternalIOInterface( ...
    'InterfaceID',     'RGB LED LD0', ...
    'InterfaceType',   'OUT', ...
    'PortName',        'RGB0', ...
    'PortWidth',       3, ...
    'FPGAPin',         {'G6', 'F6', 'E1'}, ...                 % R, G, B
    'IOPadConstraint', {'IOSTANDARD = LVCMOS33'});
end
